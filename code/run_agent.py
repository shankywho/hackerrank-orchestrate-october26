"""Budgeted, resumable run of the full agent over the evaluation requests.

The full agent (one bounded tool loop per case on the large model) runs only where deterministic code cannot finish or
the request is not a deletion, in this priority, until the large model's daily token cap is used up:
  1 not_applicable   requests the intent vote classifies as not authorizing deletion
  2 image_link       requests whose plan relies on a resource owned through a LINK_RESOURCE_IDENTITY record
  3 ambiguous        account-linker abstentions with >= 2 candidates, fewest candidates first
Every other case gets only the lean intent step (code/intent.py, cheap model) and the deterministic plan.

  python3 code/run_agent.py --dry-run          # priority list, budget and estimate (no model call)
  python3 code/run_agent.py                    # run until the budget is used; safe to stop and restart
  python3 code/run_agent.py --offline          # replay saved calls from code/cache with no network
  nohup python3 code/run_agent.py > code/cache/agent_run.log 2>&1 &     # background
Results are saved per case (code/cache/agent/<case>.txt); a re-run skips finished cases. The summary of who got the agent
and who was skipped for the cap is written to code/evaluation/agent_coverage.md.
"""
import argparse
import csv
import json
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import agent
import intent
import llm
import main as pipeline
from state import linked_resources

ROOT = Path(__file__).resolve().parent.parent
SUMMARY = ROOT / "code" / "evaluation" / "agent_coverage.md"
DAILY_CAP = 200_000       # tokens per day for the large model on the base tier (documented; headers do not expose it)
RESERVE = 0.10            # keep 10% of the cap unused
UNLOGGED = 200            # tokens of header-probe calls made outside the logger today


def uses_link(sh, case):
    """True when this request's resources include one owned through a usable link record."""
    user = sh.graph.resolve_one(case["email"])
    if not user:
        return False
    return any(lk.event_time <= case["audit_at"] and lk.event_time >= case["requested_at"]
               and sh.store.visible(lk.resource_id, case["audit_at"])
               for ident in sh.graph.identifiers(user) for lk in sh.store.links_by_ident.get(ident, ()))


def priority_order(sh, cases):
    """[(case, group, n_candidates)] in the order the agent should see them."""
    out = []
    for c in cases:
        d = sh.decisions[c["case_id"]]
        lk = sh.links.get(c["case_id"])
        n = len(agent.CaseTools(sh, c).cands) if d.authorized else 0
        if not d.authorized:
            out.append((c, "not_applicable", 0, 0))
        elif uses_link(sh, c):
            out.append((c, "image_link", 1, n))
        elif lk is not None and lk.method == "abstain" and n >= 2:
            out.append((c, "ambiguous", 2, n))
    return [(c, g, n) for c, g, rank, n in sorted(out, key=lambda x: (x[2], x[3], x[0]["case_id"]))]


def tokens_per_case(log_path=ROOT / "code" / "evaluation" / "usage_calls.csv"):
    per = Counter()
    if log_path.exists():
        for r in csv.DictReader(open(log_path, encoding="utf-8")):
            if r["purpose"] in ("agent_dev", "agent_final") and r["case_id"]:
                per[r["case_id"]] += int(r["input_tokens"]) + int(r["output_tokens"])
    vals = [v for v in per.values() if v > 0]
    return (sum(vals) / len(vals)) if vals else 3500.0, len(vals)


def classify(plan, done):
    """Split routed cases into ran / failed / skipped_for_cap. The run goes through the priority list in order, so a case
    that comes before the last case with a saved result was tried; if it has no result its call failed (e.g. an API
    error, not saved so it is retried on the next run). Cases after the last result were not reached (daily cap).
    Inference: at most the final chunk of workers could be misclassified."""
    ids = [c["case_id"] for c, _, _ in plan]
    last = max((i for i, cid in enumerate(ids) if done(cid)), default=-1)
    ran = {cid for cid in ids if done(cid)}
    failed = {cid for i, cid in enumerate(ids) if i < last and not done(cid)}
    return ran, failed, set(ids) - ran - failed


def write_summary(plan, done_ids, skipped, model, allowed, used_before, est, failed=frozenset()):
    by_group = {}
    for c, g, n in plan:
        by_group.setdefault(g, []).append((c["case_id"], n))
    L = ["# Which cases got the full agent", "",
         "Generated by `code/run_agent.py`. Every evaluation request gets the lean intent step (cheap model, majority vote with the "
         "regex classifier and the CLASSIFY_REQUEST activity). Only the cases below also got the full agent (large model, bounded "
         "tool loop). Routed cases that did not run are of two kinds: no saved result because the model call failed (retried by a "
         "re-run), and not reached because the daily token cap was used up.", "",
         f"- full-agent model: `{model}`; cap {DAILY_CAP:,} tokens/day, reserve {int(RESERVE * 100)}%, usable {allowed:,}; "
         f"already used in the last 24 h before this run: {used_before:,}; estimate {est:,.0f} tokens per case", "",
         "| group | routed | full agent ran | call failed, no result | skipped for the cap |", "|---|---|---|---|---|"]
    for g in ("not_applicable", "image_link", "ambiguous"):
        ids = by_group.get(g, [])
        L.append(f"| {g} | {len(ids)} | {sum(i in done_ids for i, _ in ids)} | {sum(i in failed for i, _ in ids)} | "
                 f"{sum(i in skipped for i, _ in ids)} |")
    for g in ("not_applicable", "image_link", "ambiguous"):
        ids = by_group.get(g, [])
        ran = [i for i, _ in ids if i in done_ids]
        skip = [(i, n) for i, n in ids if i in skipped]
        fail = [i for i, _ in ids if i in failed]
        L += ["", f"## {g}", "", f"- full agent ran on {len(ran)}: " + (", ".join(sorted(ran)) if ran else "none"),
              f"- model call failed, no result saved ({len(fail)}): " + (", ".join(fail) if fail else "none")]
        if g == "ambiguous":
            L.append(f"- skipped for the cap ({len(skip)}), fewest candidates first: " +
                     (", ".join(f"{i} ({n} candidates)" for i, n in skip) if skip else "none"))
        else:
            L.append(f"- skipped for the cap ({len(skip)}): " + (", ".join(i for i, _ in skip) if skip else "none"))
    L += ["", "Account-linker abstentions with fewer than two candidates are not routed (the agent has nothing to choose from).", ""]
    SUMMARY.write_text("\n".join(L), encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--workers", type=int, default=2)
    ap.add_argument("--offline", action="store_true")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--model", default=None)
    ap.add_argument("--summary-only", action="store_true", help="rewrite agent_coverage.md from the saved results, no model call")
    a = ap.parse_args()

    results, store = pipeline.run(str(ROOT / "dataset" / "deletion_requests.csv"), "offline")  # intent votes from the cache
    decisions, pool = pipeline.run.decisions, {c["case_id"]: c for c in pipeline.run.pool}
    evals = pipeline.read_cases(ROOT / "dataset" / "deletion_requests.csv")
    from identity import IdentityGraph
    sh = agent.build_shared(store, IdentityGraph.load(), pool, decisions)
    plan = priority_order(sh, evals)
    model = llm.pick_chat_model(llm.discover_models(a.offline), a.model)[0]["id"]
    per, n = tokens_per_case()
    used = llm.tokens_used_last_day(model) + UNLOGGED
    allowed = int(DAILY_CAP * (1 - RESERVE))
    done = lambda cid: (agent.RESULT_DIR / f"{cid}.txt").exists()
    todo = [c for c, g, k in plan if a.force or not done(c["case_id"])]
    fit = max(0, int((allowed - used) / per))
    print(f"model {model}; routed {len(plan)} {dict(Counter(g for _, g, _ in plan))}; already done {len(plan) - len(todo)}")
    print(f"budget: cap {DAILY_CAP:,}/day, usable {allowed:,}, used in last 24 h {used:,}, estimate {per:,.0f} tokens/case "
          f"(measured over {n} cases) => about {fit} more cases fit; {max(0, len(todo) - fit)} would be skipped for the cap")
    if a.summary_only:
        ran, failed, skipped = classify(plan, done)
        write_summary(plan, ran, skipped, model, allowed, used, per, failed)
        print(f"summary rewritten: ran {len(ran)}, failed {len(failed)}, skipped for the cap {len(skipped)}")
        return
    if a.dry_run:
        for c, g, k in plan[:fit + 5]:
            print(f"  {c['case_id']:10s} {g:15s} candidates={k} {'done' if done(c['case_id']) else ''}")
        return
    used0 = used
    skipped = set()
    step = max(1, a.workers)
    i = 0
    while i < len(todo):
        if a.limit and i >= a.limit:
            skipped |= {c["case_id"] for c in todo[i:]}
            break
        used_now = llm.tokens_used_last_day(model) + UNLOGGED
        if used_now + per * step > allowed and not a.offline:
            skipped |= {c["case_id"] for c in todo[i:]}
            print(f"daily budget reached ({used_now:,} used of {allowed:,} usable): skipping {len(todo) - i} case(s)", flush=True)
            break
        chunk = todo[i:i + step]
        agent.run_cases(sh, chunk, model, a.workers, a.offline, a.force, log=lambda m: print(m, flush=True), purpose="agent_final")
        i += step
    ran, failed, skipped = classify(plan, done)
    write_summary(plan, ran, skipped, model, allowed, used0, per, failed)
    print(f"finished: full agent done on {len(ran)} of {len(plan)} routed cases; call failed {len(failed)}; skipped for the cap {len(skipped)}")


if __name__ == "__main__":
    main()
