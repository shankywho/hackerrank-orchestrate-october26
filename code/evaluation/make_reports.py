"""Generate code/evaluation/evaluation_report.md from real runs (nothing typed by hand except the narrative text).

  python3 -I code/evaluation/make_reports.py
Runs the pipeline on the 32 samples and the 518 requests, scores against the sample gold, replays the saved agent
results offline, re-runs the rejected experiments, runs the custom cases, and validates output.csv.
Gold (dataset/sample_output.csv) is read only here and in the other code/evaluation scripts, never by the solver.
"""
import contextlib
import csv
