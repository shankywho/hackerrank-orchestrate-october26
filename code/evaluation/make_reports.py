import json
import subprocess
import sys
import tempfile
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(ROOT / "code"))
sys.path.insert(0, str(HERE))
import custom_cases
import main
import scorer
import store_vs_samples
import validator

OUT = HERE / "evaluation_report.md"


def sh(args, timeout=900):
    r = subprocess.run([sys.executable, "-I", *args], capture_output=True, text=True, cwd=ROOT, timeout=timeout)
    return (r.stdout + (("\n[stderr]\n" + r.stderr[-400:]) if r.returncode else "")).strip()


def block(text):
    text = "\n".join(l for l in text.splitlines() if "tool calls, verdict=" not in l)
    return "```text\n" + text.rstrip() + "\n```"


def metrics_table(res):
    L = [f"- cases scored: {res['n']}; missing: {len(res['missing'])}; invalid steps_json: {len(res['invalid_json'])}",
         f"- deletion_status accuracy: **{res['status_acc']:.4f}**",
         "- confusion (gold -> predicted): " + "; ".join(f"{g} -> {p}: {c}" for (g, p), c in sorted(res["confusion"].items())),
         f"- step-level (whole step, `step_no` ignored, micro): precision **{res['step_p']:.4f}**, recall **{res['step_r']:.4f}**, "
         f"F1 **{res['step_f1']:.4f}** (tp {res['step_tp']}, fp {res['step_fp']}, fn {res['step_fn']}); "
         f"macro per-case F1 {res['step_macro_f1']:.4f}",
         f"- sequence: exact case match **{res['seq_exact_n']}/{res['n']}** ({res['seq_exact']:.4f}); mean LCS ratio {res['seq_lcs']:.4f}",
         "", f"Field-level accuracy over {res['field_gold_steps']} gold steps (gold step aligned to a predicted step by "
         "`resource_id` + `operation`; an unmatched gold step counts as wrong in every field):", "",
         "| field | accuracy |", "|---|---|"]
    L += [f"| {f} | {v:.4f} |" for f, v in res["field_acc"].items()]
    return "\n".join(L)


def exact_rows(gold, pred):
    ok = 0
    for cid, (gs, gsteps) in gold.items():
        ps, psteps = pred.get(cid, (None, None))
        ok += gs == ps and (gsteps or []) == (psteps or [])
    return ok


def main_report():
    L = ["# Evaluation report", "",
         "Generated by `code/evaluation/make_reports.py` from real runs of this repository's code. "
         "Gold labels exist only for the 32 public samples, so every accuracy number below is a **sample** number. "
         "No hidden-set accuracy is claimed or known.", ""]

    # ---------------------------------------------------------------- samples
    results, store = main.run(str(ROOT / "dataset" / "sample_deletion_requests.csv"), "offline")
    tmp = Path(tempfile.mkdtemp()) / "sample_pred.csv"
    main.write(results, tmp)
    gold_path = ROOT / "dataset" / "sample_output.csv"
    full = scorer.score(scorer.load(gold_path), scorer.load(tmp))
    noacct = scorer.score(scorer.load(gold_path, ("account_service",)), scorer.load(tmp, ("account_service",)))
    gold = scorer.load(gold_path)
    pred = scorer.load(tmp)
    L += ["## 1. Accuracy on the 32 sample cases", "",
          f"Exact-row accuracy (status and every step field identical, `step_no` included): "
          f"**{exact_rows(gold, pred)}/{len(gold)}**.", "",
          "### 1a. All steps", "", metrics_table(full), "",
          "### 1b. Without account steps (system `account_service` dropped from gold and prediction)", "",
          f"Account steps depend on the account linker (section 3), which abstains on "
          f"{sum(1 for r in results if any(n.startswith('account abstained') for n in r.notes))} of the 32 samples, "
          "so this view separates the policy engine from the linker.", "", metrics_table(noacct), ""]
    gold_files = {s["evidence_id"] for r in csv.DictReader(open(gold_path, newline="", encoding="utf-8"))
                  for s in json.loads(r["steps_json"]) if s["evidence_id"]}
    manifest = main.coverage.normalizer.load_manifest()
    pngs = {r["file_id"] for r in manifest if r["file_path"].endswith(".png")}
    L += ["### 1c. How little the samples exercise", "",
          f"The sample gold cites {len(gold_files)} distinct evidence files out of {len(manifest)}, and "
          f"{len(gold_files & pngs)} of the {len(pngs)} images. Rules for the other record families "
          "(images, links, marketing, object storage, legal hold, pending deletions) are built from format inspection and "
          "checked by invariants and custom cases, not by gold. Expect hidden-set accuracy to be lower than the sample score.", ""]

    # ---------------------------------------------------------------- store vs gold
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        store_full, _ = main.coverage.run()
        store_vs_samples.part1(store_full, False)
    L += ["## 2. Observation store checked against sample gold (non-account resources)", "",
          "For every non-account resource in the sample gold: is it in the store with the category and state its steps "
          "imply at `audit_at` (per-file and per-row cutoff)?", "", block(buf.getvalue()), ""]

    # ---------------------------------------------------------------- linker + experiments
    L += ["## 3. Account linker (evidence, activity window with status match, singleton elimination)", "",
          block(sh(["code/evaluation/linker_eval.py"])), ""]
    L += ["## 5. Groq agent cross-check on the samples (replayed from the on-disk cache, no new calls)", "",
          "The agent is a bounded cross-check; its choices are not applied to `output.csv` (see README).", "",
          block(sh(["code/evaluation/agent_eval.py", "--set", "samples", "--offline", "--force"])), ""]
    L += ["## 6. Experiments that were tried and rejected", "",
          "### 6a. Activity-id adjacency for already-anonymized analytics resources", "",
          block(sh(["code/evaluation/anon_adjacency_eval.py"])), "",
          "### 6b. Co-activity signal for ambiguous account candidates (margin currently set in `code/coactivity.py`)", "",
          block(sh(["code/evaluation/coactivity_eval.py"])), ""]

    # ---------------------------------------------------------------- intent vote and final agent run
    results518, store518 = main.run(str(ROOT / "dataset" / "deletion_requests.csv"), "offline")
    dec = main.run.decisions
    sample_ids = {c["case_id"] for c in csv.DictReader(open(ROOT / "dataset" / "sample_deletion_requests.csv", encoding="utf-8"))}
    vc = Counter()
    for d in dec.values():
        for voter, v in d.votes.items():
            vc[(voter, v)] += 1
    gold_deletion = {cid for cid, (st_, _) in gold.items() if st_ != "NOT_APPLICABLE"}
    L_int = ["## 4. Intent step: three voters, majority vote", "",
             "Voters: the regex classifier, a CLASSIFY_REQUEST activity (votes only for the ten requests it names, matched through "
             "evidence), and one short cached call per case on the cheapest usable model. Majority wins; a 1-1 tie goes to the regex and "
             "is logged. Votes below are replayed from `code/cache` (no new calls).", "",
             "| voter | DELETE | NOT_DELETE |", "|---|---|---|"]
    for voter in ("regex", "activity", "model"):
        L_int.append(f"| {voter} | {vc[(voter, 'DELETE')]} | {vc[(voter, 'NOT_DELETE')]} |")
    L_int += ["", f"- requests in the vote pool: {len(dec)} (518 evaluation + 32 sample requests the linker needs)",
              f"- final NOT_DELETE: {sum(not d.authorized for d in dec.values())}; disagreements: "
              f"{sum(d.disagreement for d in dec.values())}; ties decided by the regex: {sum(d.tie for d in dec.values())}",
              f"- on the 32 samples (gold: every sample is a deletion): final vote correct on "
              f"{sum(dec[c].authorized for c in gold_deletion)}/{len(gold_deletion)}; regex "
              f"{sum(dec[c].votes['regex'] == 'DELETE' for c in gold_deletion)}/{len(gold_deletion)}; model "
              f"{sum(dec[c].votes.get('model') == 'DELETE' for c in gold_deletion)}/{len(gold_deletion)} "
              f"(missing model votes: {sum('model' not in dec[c].votes for c in gold_deletion)})", ""]
    log = ROOT / "code" / "evaluation" / "intent_votes.md"
    if log.exists():
        L_int += ["Every disagreement (also in `code/evaluation/intent_votes.md`):", ""] + [
            ln for ln in log.read_text(encoding="utf-8").splitlines() if ln.startswith("|") or ln.startswith("- disagreements")]
        L_int.append("")
    agent_dir = ROOT / "code" / "cache" / "agent"
    final_rows = []
    cov = ROOT / "code" / "evaluation" / "agent_coverage.md"
    ev_ids = {r.case_id for r in results518}
    for f in sorted(agent_dir.glob("*.txt")):
        r = json.loads(f.read_text(encoding="utf-8"))
        if r.get("case_id") in ev_ids and "error" not in r:
            final_rows.append(r)
    L_ag = ["### 4b. Full agent in the final run (evaluation requests)", ""]
    if cov.exists():
        L_ag += cov.read_text(encoding="utf-8").splitlines()[2:] + [""]
    if final_rows:
        intent_ok = Counter()
        acct = Counter()
        rev = Counter()
        for r in final_rows:
            v = r.get("verdict")
            if not v:
                acct["unusable verdict"] += 1
                continue
            intent_ok["agrees with the vote" if v["intent"] == r["deterministic"]["intent"] else "disagrees with the vote"] += 1
            det = r["deterministic"]["account"]
            acct["confirms the unique link" if det and v["account_id"] == det else "declines a unique link" if det and v["account_id"] is None
                 else "overrides a unique link" if det else "abstain -> picks a candidate" if v["account_id"] else "abstain -> null"] += 1
            rev[v["plan_review"]] += 1
        L_ag += [f"Results on the {len(final_rows)} evaluation requests the full agent ran on (no gold exists for them; these are agreement "
                 "counts, not accuracy):", "", f"- intent: {dict(intent_ok)}", f"- account: {dict(acct)}", f"- plan review: {dict(rev)}", ""]
    else:
        L_ag += ["The full agent has not run on any evaluation request yet.", ""]
    i5 = next(i for i, x in enumerate(L) if x.startswith("## 5."))
    L[i5:i5] = L_int
    i6 = next(i for i, x in enumerate(L) if x.startswith("## 6."))
    L[i6:i6] = L_ag
    # ---------------------------------------------------------------- custom cases
    cc = custom_cases.run_all(results518, store518)
    L += ["## 7. Custom evaluation cases (written by the participant, run on the real evidence)", "",
          f"{sum(c['passed'] for c in cc)} of {len(cc)} pass. The decoy, replica and ledger cases locate their evidence "
          "in the data instead of naming it; the two recreation cases are fixtures named by the task.", ""]
    for i, c in enumerate(cc, 1):
        L += [f"### 7.{i} {c['name']} - {'PASS' if c['passed'] else 'FAIL'}", "", f"- setup: {c['setup']}",
              f"- expected: {c['expect']}", f"- observed: {c['observed']}", ""]

    # ---------------------------------------------------------------- full run
    out_csv = ROOT / "output.csv"
    fresh = Path(tempfile.mkdtemp()) / "fresh.csv"
    main.write(results518, fresh)
    same = out_csv.exists() and out_csv.read_text(encoding="utf-8") == fresh.read_text(encoding="utf-8")
    errs, unresolved = validator.validate_file(out_csv, ROOT / "dataset" / "deletion_requests.csv", validator.manifest_times())
    st = Counter(r.status for r in results518)
    ops = Counter((s["phase"], s["operation"]) for r in results518 for s in r.steps)
    notes = Counter()
    for r in results518:
        for n in r.notes:
            notes[("account linked by evidence" if "linked by evidence" in n else
                   "account linked by singleton elimination" if "linked by singleton" in n else
                   "account abstained" if n.startswith("account abstained") else
                   "audit id discovered from a post-audit file (id only)" if n.startswith("audit id") else
                   "anchor-file citation used" if n.startswith("anchor") else
                   "INFERRED note (pending deletion / screenshot conflict)" if n.startswith("INFERRED") else
                   "object skipped (no 'belongs only to' link)" if n.startswith("object") else
                   "link excluded (dated after audit_at)" if n.startswith("link ") else
                   "uncitable step dropped" if n.startswith("dropped") else n[:40])] += 1
    L += ["## 8. Full run on the 518 requests and invariants", "",
          f"- `output.csv` is byte-identical to a fresh `python3 code/main.py` run: **{same}**",
          f"- validator (`code/validator.py`): **{'VALID' if not errs else str(len(errs)) + ' errors'}**, "
          f"{len(unresolved)} unresolved case(s) with no steps",
          f"- cases by status: {dict(st)}; total steps: {sum(ops.values())}", "",
          "| phase | operation | steps |", "|---|---|---|"]
    order = {o: i for i, o in enumerate(main.policy_ops())}
    L += [f"| {p} | {o} | {n} |" for (p, o), n in sorted(ops.items(), key=lambda x: order[x[0][1]])]
    L += ["", "Planner decisions across the 518 requests (counted from per-case notes):", "",
          "| decision | cases |", "|---|---|"] + [f"| {k} | {v} |" for k, v in sorted(notes.items())]
    cited_late = sum(1 for r in results518 for s in r.steps if s["evidence_id"] and
                     store518.file_times[s["evidence_id"]] > next(c for c in csv.DictReader(open(ROOT / "dataset" / "deletion_requests.csv", encoding="utf-8")) if c["case_id"] == r.case_id)["audit_at"])
    L += ["", f"- steps citing evidence captured after the case's `audit_at`: **{cited_late}**", ""]

    # ---------------------------------------------------------------- failures and fixes
    L += ["## 9. Failures found and improvements made", "",
          "Every row was found by running the scorer, a test or an evaluation script during development; the numbers come "
          "from those runs.", "",
          "| # | failure found | how it was found | fix / decision | result |",
          "|---|---|---|---|---|",
          "| 1 | Intent regex misread 6 of 32 sample texts (e.g. 'copy of my profile', 'download link', 'close this account') as non-deletion | sample status accuracy 0.78 | explicit refusal first, then deletion wording, then weaker non-deletion hints, then non-ASCII text | 32/32 samples are deletions; exactly 10 of 518 are NOT_APPLICABLE |",
          "| 2 | Audit records with no `retention_until` were treated as expired and planned for deletion | 9 extra security_service deletions on samples | unknown retention counts as retained (rule_12); only a known past date expires a record | extra deletions gone |",
          "| 3 | The same person has a separate account per deletion request; one request got another request's account | one false positive on samples (precision 0.994) | a resource links only if its newest linking evidence is at or after `requested_at` | sample precision 1.0, recall unchanged |",
          "| 4 | Two ledger rows are dated after their own file's capture time and after the audit (account NOT_FOUND, then FOUND) | store check: 2 rows with `observed_at` later than `captured_at` | cutoff applies per row (`observed_at`) as well as per file | custom cases 7.4 and 7.5 |",
          "| 5 | Audit ids found only in post-audit files had no pre-audit file to cite, and 8 such rows were dated after `audit_at` | validator rejected 7 COMPLETE cases | the id may come from a late file, its row must still be dated at or before `audit_at`, and an uncitable COMPLETE step is dropped; the spec's anchor-file rule covers absence proofs (4 of 4 gold account-absence steps) | late-id lookups 124 -> 116; validator clean |",
          "| 6 | Legal-hold steps came from rows with no retention date | traced the 6 legal_service steps | a legal-hold step needs a known `retained_until` after `audit_at` | 1 step dropped |",
          "| 7 | Account steps only from unique links: 3 samples (two-way ties) that had an evidence-found account before now abstain | scorer after wiring the linker | kept: no fallback, abstain when ambiguous | sample step recall 0.845 -> 0.912 with precision 1.0 (the linker adds accounts, the ties are the cost) |",
          "| 8 | The model wrapped its final JSON in a fake `json` tool call (HTTP 400 `tool_use_failed`), 14 of 32 cases errored | first full agent run | cache that outcome, force a no-tool final turn, unwrap the verdict | 32/32 completed; offline replay verified |",
          "| 9 | Groq returned 429 on the per-minute token limit | one of the first 5 agent cases | token-per-minute limiter plus backoff using the server's wait time | no further 429 |",
          "| 10 | 11 cases had no steps (images, links) | validator warning | image transcription cache, `LINK_RESOURCE_IDENTITY` bridge, links dated after `audit_at` excluded | 0 unresolved |",
          "| 11 | REJECTED: activity-id adjacency for already-anonymized analytics | section 6a | not applied | wrong proposals at every gap setting |",
          "| 12 | REJECTED: co-activity signal for ambiguous accounts | section 6b | not applied; recommended against | wrong pick at the loose margin, never fires on a sample at the strict one |",
          "| 13 | REJECTED: model choice among ambiguous accounts | section 5 | not applied | it answers null on every ambiguous case |",
          "| 14 | REJECTED: case-number tie-break for ambiguous accounts | section 3 | implemented as `account_linker.tiebreak`, never applied | right on the few samples it touches, overfit-prone |",
          "| 15 | The final run had to include model calls, but the large model's 200K daily token cap fits only a subset of the routed cases | token estimate of the routed run | cheap model (own limit) for the intent step on every request; full agent on a priority subset sized to the cap, the rest recorded as skipped | `code/evaluation/agent_coverage.md` |",
          "", "## 10. Inferred rules and known gaps", "",
          "- INFERRED, no sample gold: `MARKETING_PROFILE` by record fields; `DELETION_PENDING` accounts count as still present; "
          "object attachments deleted only with a 'belongs only to' link; backups shown in the console with no block indicator count as "
          "restorable; `SECONDARY_IDENTIFIER` for legacy contact-index rows (fitted on one sample); unknown audit retention counts as retained.",
          "- The image evidence comes from `code/evidence_cache/images.md`, transcribed by Claude Code vision during development.",
          "- Accounts: the linker abstains on ambiguous requests, so those cases have no account step. The seven sample analytics resources "
          "that are already anonymized are not linked to their owners and are omitted.",
          "- Two sample audit ids appear in no evidence file and cannot be recovered.", ""]
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT} ({len(L)} lines)")


if __name__ == "__main__":
    main_report()
