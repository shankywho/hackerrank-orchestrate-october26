"""Generate code/evaluation/usage_report.md from code/evaluation/usage_calls.csv (written by code/llm.py).

Usage: python3 -I code/evaluation/make_usage_report.py
Every number is computed from the call log. Rows are tagged by purpose:
  intent       one short call per case in the main pipeline (cheap model)          } the FINAL RUN that produced output.csv
  agent_final  the budgeted full-agent run (code/run_agent.py, large model)        }
  agent_dev    agent runs on the 32 samples while developing the agent
  probe        tool-calling probes of each candidate model
Prices come from code/llm.py LIST_PRICES (list prices read from the provider's model pages on 2026-10-25); a model
without a listed price is reported without a cost, never with a guessed one. Replayed (cached) calls are free and are not logged.
"""
import csv
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import llm

LOG = HERE / "usage_calls.csv"
OUT = HERE / "usage_report.md"
FINAL = ("intent", "agent_final")
# rate limits read on 2026-10-25: per-day requests and per-minute tokens from live response headers; tokens per day from
# console.groq.com/docs/rate-limits (headers do not expose it). Limits apply per model.
LIMITS = {"openai/gpt-oss-120b": (1000, 8000, 200_000), "openai/gpt-oss-20b": (1000, 8000, 200_000),
          "qwen/qwen3.8-27b": (1000, 8000, 200_000)}


def cost(model, i, o):
    p = llm.LIST_PRICES.get(model)
    return None if p is None else (i * p[0] + o * p[1]) / 1e6


def table(rows, keyf, title_cols):
    agg = defaultdict(lambda: {"calls": 0, "in": 0, "out": 0, "cases": set()})
    for r in rows:
        a = agg[keyf(r)]
        a["calls"] += 1
        a["in"] += int(r["input_tokens"])
        a["out"] += int(r["output_tokens"])
        if r["case_id"] and r["case_id"] != "probe":
            a["cases"].add(r["case_id"])
    L = ["| " + " | ".join(title_cols) + " | model calls | cases | input tokens | output tokens | total tokens | est. cost (USD) |",
         "|" + "---|" * (len(title_cols) + 6)]
    tot = {"calls": 0, "in": 0, "out": 0}
    cost_total, priced = 0.0, True
    for k, a in sorted(agg.items()):
        c = cost(k[-1] if isinstance(k, tuple) else k, a["in"], a["out"]) if True else None
        model = k[-1]
        c = cost(model, a["in"], a["out"])
        priced &= c is not None
        cost_total += c or 0
        L.append("| " + " | ".join(k) + f" | {a['calls']} | {len(a['cases'])} | {a['in']:,} | {a['out']:,} | {a['in'] + a['out']:,} | "
                 f"{'not priced' if c is None else f'${c:.4f}'} |")
        for x in ("calls", "in", "out"):
            tot[x] += a[x]
    L.append("| **overall** | " + " | ".join([""] * (len(title_cols) - 1)) + f" | {tot['calls']} | | {tot['in']:,} | {tot['out']:,} | "
             f"{tot['in'] + tot['out']:,} | ${cost_total:.4f}{'' if priced else ' (priced models only)'} |")
    return L, tot, cost_total


def main():
    rows = list(csv.DictReader(open(LOG, encoding="utf-8"))) if LOG.exists() else []
    final = [r for r in rows if r["purpose"] in FINAL]
    dev = [r for r in rows if r["purpose"] not in FINAL]
    L = ["# Usage report", "",
         "Generated by `code/evaluation/make_usage_report.py` from `code/evaluation/usage_calls.csv`. No number below is typed by hand. "
         "Provider: Groq (OpenAI-compatible API).", ""]

    L += ["## Final run that produced `output.csv`", "",
          "The final run is `python3 code/main.py` (deterministic planner plus the lean intent step: one short call per case on the "
          "cheapest usable model, majority-voted with the regex classifier and the CLASSIFY_REQUEST activity) followed by "
          "`python3 code/run_agent.py` (the full agent, large model, on a budgeted subset). The intent step runs on every request in the "
          "pool: the 518 evaluation requests plus the 32 sample requests the account linker needs for elimination.", ""]
    if final:
        t, tot, c = table(final, lambda r: (r["purpose"], r["model"]), ["step", "model"])
        L += t
        L += ["", f"Total for the final run: {tot['calls']} model calls, {tot['in']:,} input tokens, {tot['out']:,} output tokens, "
              f"{tot['in'] + tot['out']:,} tokens, estimated ${c:.4f} at list price (free-tier billing is $0)."]
        by_p = defaultdict(lambda: [0, set()])
        for r in final:
            by_p[r["purpose"]][0] += int(r["input_tokens"]) + int(r["output_tokens"])
            by_p[r["purpose"]][1].add(r["case_id"])
        L += ["", "### Tokens per request", ""]
        for p, (tok, cs) in sorted(by_p.items()):
            label = {"intent": "lean intent step", "agent_final": "full agent"}[p]
            L.append(f"- {label}: {len(cs)} cases, {tok:,} tokens, average {tok / max(1, len(cs)):,.0f} tokens per case, "
                     f"${sum(cost(r['model'], int(r['input_tokens']), int(r['output_tokens'])) or 0 for r in final if r['purpose'] == p) / max(1, len(cs)):.5f} per case")
        tot_tok = tot["in"] + tot["out"]
        L.append(f"- whole final run over the 518 evaluation requests: {tot_tok / 518:,.0f} tokens and ${c / 518:.5f} per request "
                 "(the 32 sample requests' intent calls are included in the numerator)")
    else:
        L.append("No final-run model calls are logged yet.")
    cov = HERE / "agent_coverage.md"
    if cov.exists():
        L += ["", "### Which cases got the full agent", ""]
        L += [ln for ln in cov.read_text(encoding="utf-8").splitlines() if ln.startswith("|") or ln.startswith("- full-agent model")]
        L += ["", "Every evaluation request got the intent step; the lists of case ids are in `code/evaluation/agent_coverage.md`."]
    L.append("")

    L += ["## Development usage (not part of the final run)", "",
          "Agent runs on the 32 samples while building the agent, and one tool-calling probe per candidate model.", ""]
    if dev:
        t, tot, c = table(dev, lambda r: (r["purpose"], r["model"]), ["purpose", "model"])
        L += t
    L += ["", "One extra response-header probe per model (94, 94 and 17 tokens) was sent outside the logger and is not in any table.", ""]

    L += ["## Rate limits and the daily cap", "",
          "| model | requests/day | tokens/minute | tokens/day | input / output list price per 1M tokens | tokens logged in the last 24 h (all purposes) |",
          "|---|---|---|---|---|---|"]
    for m, (rpd, tpm, tpd) in LIMITS.items():
        p = llm.LIST_PRICES.get(m)
        L.append(f"| {m} | {rpd:,} | {tpm:,} | {tpd:,} | " + (f"${p[0]} / ${p[1]}" if p else "n/a") +
                 f" | {llm.tokens_used_last_day(m):,} |")
    L += ["", "- requests per day and tokens per minute were read from response headers (`x-ratelimit-limit-requests`, `x-ratelimit-limit-tokens`); "
          "tokens per day is not exposed in headers and comes from console.groq.com/docs/rate-limits.",
          "- the log rows written before timestamps were added have no time and are counted as inside the window (conservative).",
          "- `code/llm.py` keeps each model under a per-minute token budget (`GROQ_TPM_BUDGET`, default 6500) and backs off on 429; "
          "`code/run_agent.py` stops before the daily cap (90% usable).", ""]
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
